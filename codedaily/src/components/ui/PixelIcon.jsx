// Convierte cada fila en tramos horizontales para generar pocos <rect>
const PATHS = Object.fromEntries(
  Object.entries(BITMAPS).map(([name, rows]) => {
    let d = '';
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] === '#') {
          const start = x;
          while (x < row.length && row[x] === '#') x += 1;
          d += `M${start} ${y}h${x - start}v1h-${x - start}z`;
        } else {
          x += 1;
        }
      }
    });
    return [name, d];
  })
);

function PixelIcon({ name, size = 32, className = '', label }) {
  const d = PATHS[name];
  if (!d) return null;

  return (
    <svg
      className={`pixel-icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      <path d={d} fill="currentColor" />
    </svg>
  );
}

export default PixelIcon;
